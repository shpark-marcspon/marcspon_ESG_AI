def where(
    page: int | None,
    *,
    sheet: str | None = None,
    grid: str | None = None,
    row: int | None = None,
    col: int | None = None,
    ref: str | None = None,
    block: str | None = None,
    span: Span | None = None,
) -> FactWhere:
    """기대값을 짓는 도우미(대상 함수를 부르지 않는다): 칸 이름을 붙여 FactWhere 를 짓는다."""
    return FactWhere(page, sheet, grid, row, col, ref, block, span)


def stored(raw: str, *, display: str | None, status: str = "rendered", date: bool = False) -> StoredNumber:
    """평평한 test_facts.stored 를 베꼈다(import 하지 않는다)."""
    return StoredNumber(raw, raw, "0.00", display, status, date, False)  # pyright: ignore[reportArgumentType]


def block(
    block_id: str, order: int, text: str | None, *, kind: str = "paragraph", table: str | None = None
) -> DocBlock:
    return DocBlock(block_id, kind, 1, (50, 300, 500, 320), order, text, table)  # pyright: ignore[reportArgumentType]


def table(table_id: str, cells: list[list[str]]) -> DocTable:
    return DocTable(table_id, 1, tuple(tuple(row) for row in cells), HEADER, "lines", "ok", ())


